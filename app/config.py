"""Settings and file paths for the whole app, read once from environment variables (.env)."""

import os
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")


def _bool(name: str, default: str) -> bool:
    return os.getenv(name, default).strip().lower() in ("1", "true", "yes")


GROQ_API_KEY = os.getenv("GROQ_API_KEY", "").strip()
GROQ_MODEL = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b").strip()
# The RAGAS "judge" can be a different model: on Groq each model has its own daily token budget, and a
# different judge is fairer than a model grading its own answers.
RAGAS_MODEL = os.getenv("RAGAS_MODEL", GROQ_MODEL).strip()
LIVE_EVAL = _bool("LIVE_EVAL", "true")  # background RAGAS scoring; turn off on rate-limited free LLM tiers
API_URL = os.getenv("API_URL", "http://localhost:8000").rstrip("/")
LANGSMITH_PROJECT = os.getenv("LANGSMITH_PROJECT", "priorauth-copilot")

# Everything the app reads lives in one folder. Tests point DATA_DIR at tests/fixtures (fictional policies).
DATA = Path(os.getenv("DATA_DIR", str(ROOT / "data")))
POLICY_DIR = DATA / "policies"  # the policy PDFs + accepted ICD-10 code lists
RULES_FILE = DATA / "rules.json"  # human-reviewed rule checklist
RULES_DRAFT_FILE = DATA / "rules_draft.json"  # LLM draft, needs review before it becomes rules.json
PROCEDURES_YAML = DATA / "procedures.yaml"  # which policy covers which procedure
CASES_FILE = DATA / "test_cases.json"  # labeled test cases for the evaluation
INDEX_DIR = DATA / "index"  # search index (generated by chunk_index)
DB_PATH = Path(os.getenv("DB_PATH", str(DATA / "app.db")))
RESULTS_DIR = ROOT / "results"
MODEL_CACHE = ROOT / "data" / "index" / "models"  # fastembed downloads its models here once

EMBED_MODEL = "BAAI/bge-small-en-v1.5"
RERANK_MODEL = "Xenova/ms-marco-MiniLM-L-6-v2"

# Retrieval sizes from the spec (section 6).
CHUNK_SIZE, CHUNK_OVERLAP = 800, 100  # one chunk size: big enough to hold a whole rule and its heading
SEARCH_K = 20
RERANK_TOP = 6  # passages the LLM reads per question (the policies are short)
RRF_K = 60

# Guardrail limits.
MAX_NOTES_CHARS = 20_000
MIN_NOTES_CHARS = 20
