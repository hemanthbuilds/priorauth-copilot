"""All Pydantic data models: cases, extracted facts, policy rules, check results, decisions and reviews."""

from typing import Literal

from pydantic import BaseModel, Field, field_validator

Status = Literal["met", "not_met", "missing"]
Outcome = Literal["APPROVE", "REQUEST_INFO", "SEND_TO_CLINICIAN"]


# ---------- The incoming request ----------

class CaseRequest(BaseModel):
    case_id: str
    patient_name: str  # synthetic
    patient_age: int
    cpt_code: str
    icd_codes: list[str]
    clinical_notes: str  # free text from the doctor


class LabeledCase(CaseRequest):
    """A test case with the answers a human reviewer agreed on (used by the eval)."""
    expected_outcome: Outcome
    expected_statuses: dict[str, Status] = Field(default_factory=dict)  # criterion_id -> status
    description: str = ""


# ---------- What the LLM extracts / returns ----------

class CaseFacts(BaseModel):
    """Facts extracted by the LLM from the notes."""
    # Lists allow null because some models send null for "nothing found", and Groq rejects a tool call
    # that doesn't match the schema; the validator below turns null back into an empty list.
    symptoms: list[str] | None = Field(default_factory=list)
    symptom_duration_weeks: int | None = None
    prior_treatments: list[str] | None = Field(default_factory=list, description='e.g. "physical therapy 8 weeks"')
    red_flags: list[str] | None = Field(default_factory=list, description='e.g. "leg numbness"')
    test_results: list[str] | None = Field(default_factory=list)
    other_relevant: list[str] | None = Field(default_factory=list)

    @field_validator("symptoms", "prior_treatments", "red_flags", "test_results", "other_relevant", mode="after")
    @classmethod
    def _none_to_empty(cls, v: list[str] | None) -> list[str]:
        return v or []


class CheckOutput(BaseModel):
    """What the LLM returns when it checks one criterion. Code turns this into a CriterionResult."""
    status: Status
    reasoning: str = Field(description="1-2 plain-English sentences")
    note_evidence: str | None = Field(None, description="Exact quote copied from the clinical notes, or null")
    policy_quote: str | None = Field(None, description="Exact quote (max ~30 words) copied from the policy_context")
    confidence: Literal["high", "medium", "low"]


class WhatIfNote(BaseModel):
    """A 'what if' question rewritten as one line to add to the clinical notes."""
    note_line: str = Field(description='e.g. "Patient completed 8 weeks of physical therapy."')


# ---------- Policy rules (rules.json) ----------

class Criterion(BaseModel):
    id: str  # e.g. "1a"
    text: str
    page: int


class CriteriaGroup(BaseModel):
    group_id: str  # e.g. "1"
    logic: Literal["ALL", "ANY"]
    description: str
    criteria: list[Criterion]


class PolicyCriteria(BaseModel):
    policy_key: str  # e.g. "lumbar_mri", must match procedures.yaml
    groups: list[CriteriaGroup]


class CriteriaFile(BaseModel):
    policies: list[PolicyCriteria]


# ---------- Results ----------

class Evidence(BaseModel):
    source: str
    page: int
    quote: str  # max ~30 words


class CriterionResult(BaseModel):
    criterion_id: str
    criterion_text: str
    status: Status
    reasoning: str  # 1-2 plain-English sentences
    note_evidence: str | None  # quote from the clinical notes, or None
    policy_evidence: list[Evidence]
    confidence: Literal["high", "medium", "low"]
    flags: list[str] = Field(default_factory=list)  # guardrail notes, e.g. "quote not found in notes"


class GroupStatus(BaseModel):
    group_id: str
    logic: Literal["ALL", "ANY"]
    description: str
    criterion_ids: list[str]
    status: Status


class Decision(BaseModel):
    outcome: Outcome
    reasons: list[str]  # generated by code from the results
    missing_items: list[str]  # what to ask the doctor for


class Hit(BaseModel):
    """One retrieved chunk, with the score from whichever stage produced it."""
    chunk_id: str
    source: str
    page: int
    text: str
    score: float


class RetrievalTrace(BaseModel):
    """Everything retrieval did for one criterion, shown in the 'Under the hood' panel."""
    bm25: list[Hit] = Field(default_factory=list)
    vector: list[Hit] = Field(default_factory=list)
    fused: list[Hit] = Field(default_factory=list)
    reranked: list[Hit] = Field(default_factory=list)  # the top 3 chunks sent to the LLM


class PolicyInfo(BaseModel):
    policy_key: str
    title: str
    policy_id: str
    source: str


class CaseReview(BaseModel):
    case_id: str
    mode: str = "review"  # review | what_if | eval
    facts: CaseFacts | None = None
    policy: PolicyInfo | None = None
    diagnosis_supported: bool = False
    results: list[CriterionResult] = Field(default_factory=list)
    group_statuses: list[GroupStatus] = Field(default_factory=list)
    decision: Decision
    retrieval: dict[str, RetrievalTrace] = Field(default_factory=dict)  # criterion_id -> trace
    guardrail_flags: list[str] = Field(default_factory=list)
    timings_ms: dict[str, float] = Field(default_factory=dict)
    run_id: str | None = None  # LangSmith run id (if tracing is on)
    review_id: int | None = None  # SQLite row id once saved
